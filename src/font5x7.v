module font5x7 (
    input      [4:0] ch,      // letter code in hud.v
    input      [2:0] row,     // 0..6
    output     [4:0] bits
);
    reg [34:0] glyph;         // 7 rows x 5 columns, top row first

    always @(*) begin
        case (ch)
            5'b00001: glyph = 35'b01110_10001_10001_11111_10001_10001_10001; // A
            5'b00010: glyph = 35'b01110_10001_10000_10000_10000_10001_01110; // C
            5'b00011: glyph = 35'b11110_10001_10001_10001_10001_10001_11110; // D
            5'b00100: glyph = 35'b11111_10000_10000_11110_10000_10000_11111; // E
            5'b00101: glyph = 35'b11111_10000_10000_11110_10000_10000_10000; // F
            5'b00110: glyph = 35'b01110_10001_10000_10111_10001_10001_01111; // G
            5'b00111: glyph = 35'b10001_10001_10001_11111_10001_10001_10001; // H
            5'b01000: glyph = 35'b01110_00100_00100_00100_00100_00100_01110; // I
            5'b01001: glyph = 35'b10001_10010_10100_11000_10100_10010_10001; // K
            5'b01010: glyph = 35'b10001_11011_10101_10101_10001_10001_10001; // M
            5'b01011: glyph = 35'b10001_11001_10101_10011_10001_10001_10001; // N
            5'b01100: glyph = 35'b01110_10001_10001_10001_10001_10001_01110; // O
            5'b01101: glyph = 35'b11110_10001_10001_11110_10000_10000_10000; // P
            5'b01110: glyph = 35'b11110_10001_10001_11110_10100_10010_10001; // R
            5'b01111: glyph = 35'b01111_10000_10000_01110_00001_00001_11110; // S
            5'b10000: glyph = 35'b11111_00100_00100_00100_00100_00100_00100; // T
            5'b10001: glyph = 35'b10001_10001_10001_10001_10001_10001_01110; // U
            5'b10010: glyph = 35'b10001_10001_10001_10101_10101_10101_01010; // W
            5'b10011: glyph = 35'b10001_10001_01010_00100_00100_00100_00100; // Y
            5'b10100: glyph = 35'b00000_00000_00000_00000_00000_01100_01100; // .
            5'b10101: glyph = 35'b00100_00100_00100_00100_00100_00000_00100; // !
            5'b10110: glyph = 35'b00100_01100_00100_00100_00100_00100_01110; // 1
            5'b10111: glyph = 35'b01110_10001_00001_00010_00100_01000_11111; // 2
            default:  glyph = 35'b00000_00000_00000_00000_00000_00000_00000; // space
        endcase
    end

    // pick out one row: row 0 is the top 5 bits [34:30], row 1 is [29:25], ...
    assign bits = glyph[(34 - row * 5) -: 5];
endmodule